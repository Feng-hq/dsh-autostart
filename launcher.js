// dsh-autostart — launcher material.
//
// Why a launcher exists at all: the Desktop shell boots its Host process with
// `--port 0`, so Windows picks the bootstrap port from the dynamic range
// (1024–15000 here, `netsh int ipv4 show dynamicport tcp`). A handful of ports in
// that range are on the fetch standard's blocked-port list, and the shell's
// `authenticateWebHost()` uses the global fetch, which refuses them:
//
//   TypeError: fetch failed  →  Error: bad port
//       at makeNetworkError (undici) … at authenticateWebHost (main.js:8230)
//
// That aborts startup and shows the fatal-recovery dialog. The launcher holds the
// blocked ports for the duration of one bootstrap, so the OS cannot hand one out,
// and retries once (or three times) if the app dies anyway.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/**
 * Ports inside the dynamic range 1024–15001 that the fetch standard marks as blocked.
 * `netsh int ipv4 show dynamicport tcp` → start 1024, count 13977 on this machine.
 */
export const BLOCKED_PORTS = Object.freeze([
  1719, 1720, 1723, 2049, 3659, 4045, 5060, 5061, 6000,
  6566, 6665, 6666, 6667, 6668, 6669, 6697, 10080,
]);

export const LAUNCHER_DIR_NAME = 'dsh-autostart';
export const LAUNCHER_SCRIPT_NAME = 'launch.ps1';
export const LAUNCHER_VBS_NAME = 'launch.vbs';
export const LAUNCHER_LOG_NAME = 'launch.log';

const FALLBACK_WINDIR = 'C:\\Windows';

export function systemRoot(env = process.env) {
  return env.SystemRoot || env.windir || FALLBACK_WINDIR;
}

/** Absolute path of the Windows Script Host (no console window appears when it runs a .vbs). */
export function wscriptPath(env = process.env) {
  return join(systemRoot(env), 'System32', 'wscript.exe');
}

/** Absolute path of Windows PowerShell 5.1 (always present; no PS7 dependency). */
export function powershellPath(env = process.env) {
  return join(systemRoot(env), 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
}

/** A PowerShell single-quoted literal: no interpolation, `'` doubled. */
export function psString(value) {
  return `'${String(value).replace(/'/gu, "''")}'`;
}

/** The login item's command line: run the hidden launcher rather than the executable. */
export function launcherCommand(vbsPath, env = process.env) {
  return `"${wscriptPath(env)}" //nologo "${vbsPath}"`;
}

/** Where the generated launcher lives: beside the preference file, inside the profile. */
export function launcherPaths(configFile) {
  const dir = configFile ? join(dirname(configFile), LAUNCHER_DIR_NAME) : '';
  return {
    dir,
    script: dir ? join(dir, LAUNCHER_SCRIPT_NAME) : '',
    vbs: dir ? join(dir, LAUNCHER_VBS_NAME) : '',
    log: dir ? join(dir, LAUNCHER_LOG_NAME) : '',
  };
}

// Keep this template ASCII-only and free of backticks: it is written verbatim to
// launch.ps1 and read by Windows PowerShell 5.1, whose default code page is not UTF-8.
const SCRIPT_TEMPLATE = String.raw`# dsh-autostart launcher - starts DeepSeek Harness at Windows sign-in.
# Generated by the dsh-autostart DSH plugin; rewritten on every plugin activation.
# Holding the fetch-blocked ports keeps the desktop bootstrap URL off a port that
# the shell's fetch() refuses ("bad port"), which otherwise aborts startup.
param(
  [string]$ExePath = __EXE__,
  [string]$LogPath = __LOG__,
  [string]$ChildArguments = '',
  [int]$WaitSeconds = __WAIT__,
  [int]$MaxAttempts = __ATTEMPTS__
)

$ErrorActionPreference = 'Stop'

if ((Test-Path -LiteralPath $LogPath) -and ((Get-Item -LiteralPath $LogPath).Length -gt 262144)) {
  try { Remove-Item -LiteralPath $LogPath -Force } catch { }
}

function Write-LauncherLog([string]$Message) {
  try {
    $stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss.fff')
    Add-Content -LiteralPath $LogPath -Value ($stamp + ' ' + $Message) -Encoding UTF8
  } catch { }
}

function Get-LauncherAppIds {
  $leaf = [System.IO.Path]::GetFileName($ExePath)
  $filter = "Name = '" + $leaf.Replace("'", "''") + "'"
  $items = @()
  try { $items = @(Get-CimInstance -ClassName Win32_Process -Filter $filter -ErrorAction Stop) } catch { return @() }
  $ids = @()
  foreach ($item in $items) {
    if ($item.ExecutablePath -and ($item.ExecutablePath -ieq $ExePath)) { $ids += [int]$item.ProcessId }
  }
  return $ids
}

function Get-LauncherListenerPort([int[]]$Ids) {
  $listeners = @()
  try { $listeners = @(Get-NetTCPConnection -State Listen -ErrorAction Stop) } catch { return 0 }
  foreach ($listener in $listeners) {
    if ($Ids -contains [int]$listener.OwningProcess) { return [int]$listener.LocalPort }
  }
  return 0
}

function Get-LauncherCrashReport([datetime]$Since) {
  $dir = Join-Path $env:APPDATA '@deepseek-ai\dsh-desktop\logs'
  $newest = $null
  try {
    $newest = Get-ChildItem -LiteralPath $dir -Filter 'crash-*.log' -File -ErrorAction Stop | Where-Object { $_.LastWriteTime -ge $Since } | Sort-Object LastWriteTime -Descending | Select-Object -First 1
  } catch { return $null }
  if ($null -eq $newest) { return $null }
  try { return Get-Content -LiteralPath $newest.FullName -Raw -ErrorAction Stop } catch { return '' }
}

$reserved = @()
foreach ($port in @(__PORTS__)) {
  try {
    $listener = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Loopback, $port)
    $listener.Start()
    $reserved += $listener
  } catch {
    Write-LauncherLog ('port ' + $port + ' is already busy; leaving it alone')
  }
}
Write-LauncherLog ('holding ' + @($reserved).Count + ' fetch-blocked port(s) during this bootstrap')

try {
  if (@(Get-LauncherAppIds).Count -gt 0) {
    Write-LauncherLog 'DeepSeek Harness is already running; nothing to launch'
  } else {
    $attempt = 1
    while ($attempt -le $MaxAttempts) {
      $launchAt = Get-Date
      Write-LauncherLog ('attempt ' + $attempt + ': starting ' + $ExePath)
      if ($ChildArguments) {
        try { $null = Start-Process -FilePath $ExePath -ArgumentList $ChildArguments -PassThru } catch { Write-LauncherLog ('could not start the app: ' + $_.Exception.Message); break }
      } else {
        try { $null = Start-Process -FilePath $ExePath -PassThru } catch { Write-LauncherLog ('could not start the app: ' + $_.Exception.Message); break }
      }
      $deadline = (Get-Date).AddSeconds($WaitSeconds)
      $boundPort = 0
      while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 500
        $ids = @(Get-LauncherAppIds)
        if ($ids.Count -eq 0) { break }
        $boundPort = Get-LauncherListenerPort $ids
        if ($boundPort -gt 0) { break }
      }
      if ($boundPort -gt 0) {
        Write-LauncherLog ('attempt ' + $attempt + ': bootstrap port ' + $boundPort + ' is listening; releasing the reservations')
        break
      }
      if (@(Get-LauncherAppIds).Count -gt 0) {
        Write-LauncherLog ('attempt ' + $attempt + ': still running without a listening port after ' + $WaitSeconds + 's; leaving it alone')
        break
      }
      $report = Get-LauncherCrashReport $launchAt
      if ($null -eq $report) {
        Write-LauncherLog ('attempt ' + $attempt + ': the app exited without writing a crash report')
      } else {
        Write-LauncherLog ('attempt ' + $attempt + ': the app exited and wrote a crash report')
        if ($report -notmatch 'bad port') {
          Write-LauncherLog 'the failure is not the fetch-blocked-port crash; not retrying'
          break
        }
      }
      $attempt++
    }
  }
} finally {
  foreach ($listener in $reserved) { try { $listener.Stop() } catch { } }
  Write-LauncherLog ('released ' + @($reserved).Count + ' reservation(s); launcher done')
}
`;

/** The PowerShell launcher source for one executable. */
export function buildLaunchScript(options) {
  const { exe, logPath, waitSeconds = 900, maxAttempts = 3, blockedPorts = BLOCKED_PORTS } = options ?? {};
  if (!exe) throw new Error('launcher needs the executable path');
  if (!logPath) throw new Error('launcher needs a log path');
  return SCRIPT_TEMPLATE
    .replace('__EXE__', psString(exe))
    .replace('__LOG__', psString(logPath))
    .replace('__WAIT__', String(Math.max(1, Math.trunc(waitSeconds))))
    .replace('__ATTEMPTS__', String(Math.max(1, Math.trunc(maxAttempts))))
    .replace('__PORTS__', blockedPorts.join(','));
}

/** A VBS trampoline: runs PowerShell with a hidden window, then exits at once. */
export function buildLauncherVbs(scriptPath, exePath, env = process.env) {
  const command = `"${powershellPath(env)}" -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${scriptPath}"`;
  // VBScript has no escape character: a quote inside a literal is written as two quotes.
  const literal = `"${command.replace(/"/gu, '""')}"`;
  const exeLiteral = `"${`"${exePath}"`.replace(/"/gu, '""')}"`;
  return [
    "' dsh-autostart launcher trampoline - generated, do not edit.",
    "' Runs the PowerShell launcher with no console window, then returns immediately.",
    "' If the launcher script went missing, start the app directly instead of doing nothing.",
    'Option Explicit',
    'Dim shell, fso',
    'Set shell = CreateObject("WScript.Shell")',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    `If fso.FileExists("${scriptPath}") Then`,
    `  shell.Run ${literal}, 0, False`,
    'Else',
    `  shell.Run ${exeLiteral}, 1, False`,
    'End If',
    '',
  ].join('\r\n');
}

function writeIfChanged(file, content) {
  try {
    if (existsSync(file) && readFileSync(file, 'utf8') === content) return false;
  } catch {
    /* unreadable — rewrite it */
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
  return true;
}

/** Materialize launch.ps1 + launch.vbs. Returns the paths plus what was rewritten. */
export function ensureLauncher(exe, configFile) {
  const paths = launcherPaths(configFile);
  if (!paths.dir) throw new Error('profile directory is unknown');
  const script = buildLaunchScript({ exe, logPath: paths.log });
  const vbs = buildLauncherVbs(paths.script, exe);
  const wroteScript = writeIfChanged(paths.script, script);
  const wroteVbs = writeIfChanged(paths.vbs, vbs);
  return { ...paths, command: launcherCommand(paths.vbs), wroteScript, wroteVbs };
}

/** The command the login item must hold for this preference — no side effects. */
export function expectedCommand(eff, exe, configFile, env = process.env) {
  if (!exe) return '';
  if (eff?.launchMode === 'direct') return `"${exe}"`;
  const paths = launcherPaths(configFile);
  return paths.vbs ? launcherCommand(paths.vbs, env) : `"${exe}"`;
}
